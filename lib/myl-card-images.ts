export function mylBanlistCardImage(
  card: Pick<MylRestrictedCard, 'name' | 'edition'>,
  board: MylNewsBoard,
): string | undefined {
  const name = card.name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
  const path = images[board][name];
  return path ? 'https://api.myl.cl/static/cards/' + path : undefined;
}
