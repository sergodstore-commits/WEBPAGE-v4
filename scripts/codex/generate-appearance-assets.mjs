import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(
  await readFile(new URL('../../design/manifest/APPROVED-UI-ASSETS.json', import.meta.url), 'utf8'),
);
const legacyIds = [
  'burst-red',
  'brush-cyan',
  'brush-red',
  'brush-white',
  'fragments-red',
  'halftone-red',
];
const approvedIds = manifest.assets.map(({ path }) =>
  path
    .replace('design/approved/ui/', '')
    .replace(/\.png$/u, '')
    .replaceAll('_', '-')
    .replace('/', '-'),
);
const lines = [...legacyIds, ...approvedIds].map((id) => `  '${id}',`).join('\n');
const source =
  `// Generated by scripts/codex/generate-appearance-assets.mjs from the approved manifest.\n` +
  `// Do not edit this list by hand. Legacy aliases remain valid for published layouts.\n` +
  `export const siteAppearanceAssetIds = [\n${lines}\n] as const;\n`;

await writeFile(`${root}packages/contracts/src/site-appearance-assets.ts`, source, 'utf8');
